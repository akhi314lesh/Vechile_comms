        f.write(f"| **Learning Status** | **{trend}** | Improving Policy |\n")
        f.write(f"| **Total Episodes** | `{episode}` | Ongoing |\n")
        f.write(f"| **Curriculum Stage** | `Stage {curriculum_stage}` | Stage 1 (Empty) → Stage 7 (Mixed) |\n")
        f.write(f"| **Latest 10-Ep Avg Reward** | `{avg_10:.1f}` | Higher is better (> +50) |\n")
        f.write(f"| **Best Rolling 100 Reward** | `{best_avg_reward:.1f}` | Peak performance |\n")
