    n = len(episode_rewards)
    if n == 0:
        return

    recent_10 = episode_rewards[-10:]
    avg_10 = sum(recent_10) / len(recent_10)
    col_rate = (collision_count / episode) * 100

    # Trend calculation
    chunk = min(50, n // 2) if n >= 20 else max(1, n // 2)
    early_r = sum(episode_rewards[:chunk]) / chunk
    recent_r = sum(episode_rewards[-chunk:]) / chunk
    diff = recent_r - early_r
    trend = "IMPROVING (+{:.1f} pts)".format(diff) if diff > 5 else "PROGRESSING" if diff > 0 else "EXPLORING"

    md_path = Path(log_dir) / 'TRAINING_SUMMARY.md'
