async def train(args):
    # Initialize bridge
    bridge = SimulatorBridge(host=args.host, port=args.port)
    await bridge.start_server()

    # Initialize PPO
    trainer = PPOTrainer(
        obs_dim=97,
        act_dim=3,
        device=args.device,
        lr=args.lr,
        gamma=args.gamma,
        gae_lambda=args.gae_lambda,
        clip_eps=args.clip_eps,
        entropy_coef=args.entropy_coef,
        epochs=args.ppo_epochs,
        batch_size=args.batch_size,
    )

    # Load checkpoint if exists
    if args.resume and os.path.exists(args.resume):
        trainer.load(args.resume)

    # Create log directory
    log_dir = Path(args.log_dir)
    log_dir.mkdir(parents=True, exist_ok=True)

    # Training log
    log_file = open(log_dir / 'training_log.jsonl', 'a')

    curriculum_stage = args.curriculum_start
    await bridge.set_curriculum(curriculum_stage)

    # Training statistics
    episode_rewards = []
    episode_lengths = []
    collision_count = 0
    best_avg_reward = -float('inf')

    print(f'\n{"="*60}')
    print(f'  V2V RL Training — PPO')
    print(f'  Episodes: {args.episodes}')
    print(f'  Curriculum start: {curriculum_stage}')
    print(f'  Device: {args.device}')
    print(f'{"="*60}\n')

    for episode in range(1, args.episodes + 1):
        # Reset environment
        seed = episode * 7919 + 42 if args.deterministic else None
        obs = await bridge.reset(seed)

        episode_reward = 0
        episode_steps = 0
        done = False

        while not done:
            # Select action
            action, value = trainer.select_action(obs, deterministic=False)

            # Step environment
            next_obs, reward, terminated, truncated, info = await bridge.step(action)
            done = terminated or truncated

            # Store transition
            trainer.store_transition(obs, action, reward, done, value)

            obs = next_obs
            episode_reward += reward
            episode_steps += 1

            # PPO update when buffer is large enough
            if len(trainer.buffer) >= args.update_interval:
                with torch.no_grad():
                    last_value = trainer.model.get_value(
                        torch.FloatTensor(obs).unsqueeze(0).to(trainer.device)
                    ).item()
                loss = trainer.update(last_value)

        # Episode complete
        episode_rewards.append(episode_reward)
        episode_lengths.append(episode_steps)
        if info.get('collision', False):
            collision_count += 1

        # Logging
        recent_rewards = episode_rewards[-100:]
        avg_reward = np.mean(recent_rewards)
        collision_rate = collision_count / episode

        log_entry = {
            'episode': episode,
            'reward': episode_reward,
            'steps': episode_steps,
            'avg_reward_100': avg_reward,
            'collision': info.get('collision', False),
            'collision_rate': collision_rate,
            'curriculum_stage': curriculum_stage,
            'reason': info.get('reason', ''),
            'timestamp': time.time()
        }
        log_file.write(json.dumps(log_entry) + '\n')
        log_file.flush()

        # Update human-readable TRAINING_SUMMARY.md
        if episode % 5 == 0 or episode <= 10:
            write_summary_report(log_dir, episode, episode_rewards, collision_count, curriculum_stage, best_avg_reward)

        # Print progress
        if episode % args.print_interval == 0:
            print(f'EP {episode:5d} | '
                  f'R={episode_reward:7.1f} | '
                  f'Avg100={avg_reward:7.1f} | '
                  f'Steps={episode_steps:5d} | '
                  f'Col={collision_rate:.2%} | '
                  f'Stage={curriculum_stage}')

        # Save best model
        if avg_reward > best_avg_reward and episode >= 100:
            best_avg_reward = avg_reward
            trainer.save(str(log_dir / 'best_model.pt'))

        # Periodic save
        if episode % args.save_interval == 0:
            trainer.save(str(log_dir / f'model_ep{episode}.pt'))

        # Curriculum advancement
        if episode % 50 == 0 and len(recent_rewards) >= 30:
            cr = sum(1 for e in episode_rewards[-50:] if e < -50) / 50
            if avg_reward > 20 and cr < 0.3 and curriculum_stage < 7:
                curriculum_stage += 1
                await bridge.set_curriculum(curriculum_stage)
                print(f'\n>>> CURRICULUM ADVANCED TO STAGE {curriculum_stage} <<<\n')

    # Final save
    trainer.save(str(log_dir / 'final_model.pt'))
    log_file.close()

    print(f'\n{"="*60}')
    print(f'  Training complete!')
    print(f'  Best avg reward: {best_avg_reward:.1f}')
    print(f'  Final collision rate: {collision_count/args.episodes:.2%}')
    print(f'  Models saved to: {log_dir}')
    print(f'{"="*60}')

    await bridge.close()


def main():
    parser = argparse.ArgumentParser(description='V2V RL Training with PPO')
    parser.add_argument('--episodes', type=int, default=1000)
    parser.add_argument('--curriculum-start', type=int, default=1)
    parser.add_argument('--host', default='localhost')
    parser.add_argument('--port', type=int, default=8765)
    parser.add_argument('--device', default='auto', choices=['auto', 'cpu', 'cuda', 'mps'])
    parser.add_argument('--lr', type=float, default=3e-4)
    parser.add_argument('--gamma', type=float, default=0.99)
    parser.add_argument('--gae-lambda', type=float, default=0.95)
    parser.add_argument('--clip-eps', type=float, default=0.2)
    parser.add_argument('--entropy-coef', type=float, default=0.01)
    parser.add_argument('--ppo-epochs', type=int, default=10)
    parser.add_argument('--batch-size', type=int, default=64)
    parser.add_argument('--update-interval', type=int, default=2048)
    parser.add_argument('--print-interval', type=int, default=10)
    parser.add_argument('--save-interval', type=int, default=100)
    parser.add_argument('--log-dir', default='rl/logs')
    parser.add_argument('--resume', default=None, help='Path to checkpoint to resume from')
    parser.add_argument('--deterministic', action='store_true')
    args = parser.parse_args()

    # Import torch here to get better error message
    try:
        import torch
    except ImportError:
        print('ERROR: PyTorch not found. Install with: pip install torch')
        return

    # Make torch available in the training function
    globals()['torch'] = torch

    # Auto-detect GPU (CUDA / MPS)
    if args.device == 'auto' or args.device == 'cuda':
        if torch.cuda.is_available():
            args.device = 'cuda'
            gpu_name = torch.cuda.get_device_name(0)
            print(f'[GPU] Training on CUDA GPU: {gpu_name}')
        elif hasattr(torch.backends, 'mps') and torch.backends.mps.is_available():
            args.device = 'mps'
            print('[GPU] Training on Apple Silicon MPS')
        else:
            args.device = 'cpu'
            print('[GPU] CUDA/MPS not detected, using CPU')

    asyncio.run(train(args))


if __name__ == '__main__':
    main()
